    <script>
        const contractId = new URLSearchParams(location.search).get('id');
        const shouldPrint = new URLSearchParams(location.search).get('print') === '1';
        const signBtn = document.querySelector('#sign-btn');

        async function loadContract() {
            if (!contractId) {
                document.querySelector('.document-body').innerHTML = '<p class="state">Identifiant contrat manquant.</p>';
                return;
            }

            try {
                const contract = await api.get(`/api/contrats/${contractId}`);

                // Mettre à jour les informations du contrat
                document.getElementById('contract-ref').textContent = `CTR-${contract.id_contrat || contract.id}`;
                document.getElementById('contract-status').textContent = contract.statut_designation || contract.statut;
                document.getElementById('contract-date').textContent = `Antananarivo, le ${new Date().toLocaleDateString('fr-FR')}`;
                document.getElementById('contract-type').textContent = contract.type_contrat_designation || contract.type_contrat_id;
                document.getElementById('employee-name').textContent = `${contract.salarie_prenom || ''} ${contract.salarie_nom || ''}`.trim() || contract.id_salarie;
                document.getElementById('employee-id').textContent = `SAL-${contract.id_salarie}`;
                document.getElementById('employee-position').textContent = contract.poste_titre || contract.id_poste;
                document.getElementById('start-date').textContent = contract.date_debut ? new Date(contract.date_debut).toLocaleDateString('fr-FR') : 'Non défini';
                document.getElementById('end-date').textContent = contract.date_fin ? new Date(contract.date_fin).toLocaleDateString('fr-FR') : 'Non applicable';
                document.getElementById('salary').textContent = contract.salaire_base ? `${Number(contract.salaire_base).toLocaleString('fr-FR')} Ar` : 'Non défini';
                document.getElementById('employee-signature-name').textContent = `${contract.salarie_prenom || ''} ${contract.salarie_nom || ''}`.trim();
                document.getElementById('footer-ref').textContent = `Référence : CTR-${contract.id_contrat || contract.id}`;

                // Gérer le bouton de signature
                const status = contract.statut_designation || contract.statut;
                if (status === 'En attente de signature') {
                    signBtn.style.display = 'inline-flex';
                } else {
                    signBtn.style.display = 'none';
                }

                // Si déjà signé, afficher la date
                if (contract.date_signature) {
                    document.getElementById('signature-date').textContent = new Date(contract.date_signature).toLocaleDateString('fr-FR');
                }

                // Imprimer automatiquement si le paramètre print=1 est présent
                if (shouldPrint) {
                    setTimeout(() => window.print(), 500);
                }

            } catch (error) {
                document.querySelector('.document-body').innerHTML = `<p class="state" style="color: var(--danger)">${error.message}</p>`;
            }
        }

        signBtn.addEventListener('click', async () => {
            if (!confirm('Êtes-vous sûr de vouloir signer ce contrat ?')) return;

            try {
                await api.post(`/api/contrats/${contractId}/signer`, {
                    dateSignature: new Date().toISOString().slice(0, 10)
                });
                ui.toast('Contrat signé avec succès.');
                loadContract();
            } catch (error) {
                alert('Erreur lors de la signature: ' + error.message);
            }
        });

        loadContract();
    </script>
